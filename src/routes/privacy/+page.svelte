<script lang="ts">
	import { app, BACKUP_REMINDER_DAYS } from '#lib/store/app-state.svelte';
	import { validateBackup, type ValidationError } from '#lib/logic/validate';
	import { backupFileName } from '#lib/logic/filenames';
	import { downloadText } from '#lib/logic/export-client';
	import { relativeDayLabel, todayLocalISODate } from '#lib/logic/dates';
	import ConfirmDialog from '#lib/components/ConfirmDialog.svelte';
	import type { AppData } from '#lib/types';

	let importErrors = $state<ValidationError[]>([]);
	let importWarnings = $state<string[]>([]);
	let pendingImport = $state<AppData | null>(null);
	let importSummary = $state('');

	function exportBackup() {
		downloadText(app.exportJson(), backupFileName(todayLocalISODate()), 'application/json');
		app.markBackedUp();
		app.pushToast('Backup downloaded. Keep it somewhere safe.', 'good');
	}

	async function onFile(event: Event) {
		const input = event.currentTarget as HTMLInputElement;
		const file = input.files?.[0];
		importErrors = [];
		importWarnings = [];
		pendingImport = null;
		if (!file) return;

		try {
			const text = await file.text();
			const result = validateBackup(text);
			if (!result.ok) {
				importErrors = result.errors;
				app.pushToast('That backup file could not be read. See the errors below.', 'bad');
			} else {
				pendingImport = result.data;
				importWarnings = result.warnings;
				importSummary = `${result.data.resumes.length} resume${
					result.data.resumes.length === 1 ? '' : 's'
				}, ${result.data.coverLetters.length} cover letter${
					result.data.coverLetters.length === 1 ? '' : 's'
				} and ${result.data.applications.length} application${
					result.data.applications.length === 1 ? '' : 's'
				}`;
			}
		} catch {
			importErrors = [{ path: 'file', message: 'That file could not be read from disk.' }];
		} finally {
			input.value = '';
		}
	}

	const controlStyle =
		'background: var(--surface); border: 1px solid var(--border); color: var(--text)';
</script>

<div class="mx-auto max-w-2xl p-4 md:p-6">
	<h1 class="text-2xl font-semibold tracking-tight">Privacy and backup</h1>

	<section class="surface-card mt-5 p-4">
		<h2 class="text-base font-semibold">Where your data is stored</h2>
		<p class="mt-2 text-sm" style="color: var(--text-muted)">
			Everything you type into ResumeForge - your resumes, cover letters, applications, job
			descriptions and any photo - is stored only in
			<strong style="color: var(--text)">this browser, on this device</strong>, using the browser's
			localStorage. Nothing is uploaded, and there is no account, no database and no tracking.
		</p>
		<ul class="mt-3 space-y-1.5 text-sm" style="color: var(--text-muted)">
			<li>&bull; Clearing your browser data will delete everything. Keep a backup.</li>
			<li>&bull; Your data does not follow you to another browser, device or private window.</li>
			<li>
				&bull; PDF and Word exports are generated by a stateless server route: the document is sent,
				the file comes back, and nothing is stored or logged.
			</li>
			<li>
				&bull; The job match checker runs entirely in this browser against a bundled dictionary. No
				AI service is used and your job descriptions are never sent anywhere.
			</li>
		</ul>
	</section>

	<section class="surface-card mt-4 p-4">
		<h2 class="text-base font-semibold">Backup</h2>
		<p class="mt-1 text-sm" style="color: var(--text-muted)">
			Last backup: <strong style="color: var(--text)">{relativeDayLabel(app.data.settings.lastBackupAt)}</strong>
			{#if app.needsBackupReminder}
				- we remind you after {BACKUP_REMINDER_DAYS} days.
			{/if}
		</p>

		{#if app.needsBackupReminder}
			<p class="mt-2 rounded-lg p-3 text-sm" style="background: #fff4e6; color: #7a3d02" role="status">
				{#if app.data.settings.lastBackupAt == null}
					You have not exported a backup yet. If you clear this browser's data, your work is gone.
				{:else}
					It has been more than {BACKUP_REMINDER_DAYS} days since your last backup.
				{/if}
			</p>
		{/if}

		<div class="mt-3 flex flex-wrap gap-2">
			<button
				type="button"
				class="tap rounded-lg px-4 py-2 text-sm font-semibold text-white"
				style="background: var(--color-ember)"
				onclick={exportBackup}
			>
				Export JSON backup
			</button>
			<label
				class="tap inline-flex cursor-pointer items-center rounded-lg px-4 py-2 text-sm font-medium"
				style={controlStyle}
			>
				Import JSON backup
				<input type="file" accept="application/json,.json" class="sr-only" onchange={onFile} />
			</label>
		</div>

		{#if importErrors.length}
			<div class="mt-3 rounded-lg p-3" style="background: #ffe3e3; color: #a51111" role="alert">
				<p class="text-sm font-semibold">This file could not be imported</p>
				<ul class="mt-1.5 space-y-1 text-sm">
					{#each importErrors as error, i (i)}
						<li>&bull; {error.message}</li>
					{/each}
				</ul>
				<p class="mt-2 text-xs">
					Nothing in this browser was changed. Pick a file exported from ResumeForge.
				</p>
			</div>
		{/if}

		{#if pendingImport}
			<div class="mt-3 rounded-lg p-3" style="background: var(--surface-sunken)">
				<p class="text-sm font-semibold">Ready to import</p>
				<p class="mt-1 text-sm" style="color: var(--text-muted)">
					This file contains {importSummary}. Importing replaces everything currently in this
					browser.
				</p>
				{#if importWarnings.length}
					<ul class="mt-2 space-y-1 text-xs" style="color: var(--color-warn)">
						{#each importWarnings as warning, i (i)}
							<li>&bull; {warning}</li>
						{/each}
					</ul>
				{/if}
			</div>
		{/if}
	</section>

	<section class="surface-card mt-4 p-4">
		<h2 class="text-base font-semibold">Limits you should know about</h2>
		<ul class="mt-2 space-y-1.5 text-sm" style="color: var(--text-muted)">
			<li>
				&bull; Browser storage is roughly 5 MB. Photos are compressed under 100 KB to help, but a
				very large library can still fill it. We warn you before that happens.
			</li>
			<li>
				&bull; If storage is blocked (some private browsing modes), the app still works for the
				session but cannot save. Export a backup before closing the tab.
			</li>
			<li>
				&bull; The match score is an estimate based on keyword matching. It is not how any specific
				company's screening software scores resumes, and no score guarantees an interview.
			</li>
		</ul>
	</section>
</div>

<ConfirmDialog
	open={pendingImport !== null}
	title="Replace everything with this backup?"
	message={`This will replace all data in this browser with ${importSummary} from the file. Export a backup of your current data first if you need it.`}
	confirmLabel="Import and replace"
	tone="normal"
	onconfirm={() => {
		if (pendingImport) {
			app.replaceAll(pendingImport);
			app.pushToast('Backup imported.', 'good');
		}
		pendingImport = null;
		importWarnings = [];
	}}
	oncancel={() => {
		pendingImport = null;
		importWarnings = [];
	}}
/>
